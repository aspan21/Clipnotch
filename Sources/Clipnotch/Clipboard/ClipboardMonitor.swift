import AppKit
import Combine
import Foundation

/// There is no change notification for NSPasteboard, so this polls
/// `changeCount`. 0.3s is below human reaction time for a copy-then-look.
@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    /// Fires when a copy came from outside this app, so the paste queue can bail out.
    var onExternalCopy: (() -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    /// changeCounts produced by our own writes, which must not re-enter history.
    private var selfWrittenCounts = Set<Int>()

    /// Password managers and clipboard tools mark content with these types.
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    nonisolated static let maxPayloadBytes = 48 * 1024 * 1024

    private init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Registers a changeCount this app just produced so it is not captured back.
    func ignore(changeCount: Int) {
        selfWrittenCounts.insert(changeCount)
        if selfWrittenCounts.count > 32 { selfWrittenCounts.removeAll() }
    }

    private func poll() {
        let current = pasteboard.changeCount
        guard current != lastChangeCount else { return }
        lastChangeCount = current

        if selfWrittenCounts.remove(current) != nil { return }

        onExternalCopy?()
        capture()
    }

    private func capture() {
        if Settings.shared.skipConcealed,
           let types = pasteboard.types,
           Self.concealedTypes.contains(where: { types.contains($0) }) {
            Log.clipboard.info("skipped concealed pasteboard content")
            return
        }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // Order matters: an image copied from Finder also carries a file URL,
        // and a screenshot carries PNG plus TIFF. Richest useful form wins.
        if let imageData = readImageData() {
            captureImage(from: imageData, source: source)
        } else if let urls = readFileURLs(), !urls.isEmpty {
            let joined = urls.map(\.path).joined(separator: "\n")
            guard let data = joined.data(using: .utf8) else { return }
            ClipStore.shared.insert(kind: .files, payload: data, textPreview: joined,
                                    pixelSize: nil, thumbnail: fileThumbnail(for: urls.first!),
                                    sourceBundleID: source)
        } else if let rtf = pasteboard.data(forType: .rtf) {
            guard rtf.count <= Self.maxPayloadBytes else { return }
            let plain = pasteboard.string(forType: .string)
                ?? NSAttributedString(rtf: rtf, documentAttributes: nil)?.string
            ClipStore.shared.insert(kind: .richText, payload: rtf, textPreview: plain,
                                    pixelSize: nil, thumbnail: nil, sourceBundleID: source)
        } else if let text = pasteboard.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, let data = text.data(using: .utf8),
                  data.count <= Self.maxPayloadBytes
            else { return }
            ClipStore.shared.insert(kind: .text, payload: data, textPreview: text,
                                    pixelSize: nil, thumbnail: nil, sourceBundleID: source)
        }
    }

    /// Hands the raw bytes to a background queue: decoding a retina screenshot,
    /// re-encoding it to PNG and downscaling a thumbnail costs tens of
    /// milliseconds, which is a visible hitch on the main thread.
    private func captureImage(from data: Data, source: String?) {
        DispatchQueue.global(qos: .userInitiated).async {
            guard let image = NSImage(data: data) else { return }
            guard let png = ImageUtil.pngData(from: image),
                  png.count <= Self.maxPayloadBytes
            else { return }
            let pixelSize = ImageUtil.pixelSize(of: image)
            let thumb = ImageUtil.thumbnail(from: image)
            DispatchQueue.main.async {
                ClipStore.shared.insert(
                    kind: .image,
                    payload: png,
                    textPreview: nil,
                    pixelSize: pixelSize,
                    thumbnail: thumb,
                    sourceBundleID: source
                )
            }
        }
    }

    private func readImageData() -> Data? {
        // Screenshots land as public.png; Preview and browsers may only offer TIFF.
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                return data
            }
        }
        return nil
    }

    private func readFileURLs() -> [URL]? {
        pasteboard.readObjects(forClasses: [NSURL.self],
                               options: [.urlReadingFileURLsOnly: true]) as? [URL]
    }

    private func fileThumbnail(for url: URL) -> Data? {
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        icon.size = CGSize(width: 128, height: 128)
        return ImageUtil.thumbnail(from: icon, maxEdge: 128)
    }
}
